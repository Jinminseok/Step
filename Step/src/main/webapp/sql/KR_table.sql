--------------------------------------------------------
-- 1. 최상위 부모 테이블 (의존성 없는 테이블 먼저 생성)
--------------------------------------------------------

-- 1-1. USERS (회원)
CREATE TABLE USERS (
    USER_NUM NUMBER PRIMARY KEY,
    USER_ID  VARCHAR2(12) UNIQUE NOT NULL,
    AUTH     NUMBER(1) DEFAULT 2 NOT NULL
);
CREATE SEQUENCE USERS_SEQ NOCACHE;

-- 1-2. CATEGORIES (카테고리)
CREATE TABLE CATEGORIES (
    CAT_NUM     NUMBER PRIMARY KEY,
    CAT_NAME    VARCHAR2(30) NOT NULL,
    CAT_ICON    VARCHAR2(10),
    CAT_SORT_NO NUMBER DEFAULT 0 NOT NULL,
    CAT_USE_YN  CHAR(1) DEFAULT 'Y' NOT NULL
);
CREATE SEQUENCE CATEGORIES_SEQ NOCACHE;

-- 1-3. BRANDS (브랜드)
CREATE TABLE BRANDS (
    BRAND_NUM    NUMBER PRIMARY KEY,
    BRAND_NAME   VARCHAR2(50) NOT NULL,
    BRAND_USE_YN CHAR(1) DEFAULT 'Y' NOT NULL
);
CREATE SEQUENCE BRANDS_SEQ NOCACHE;

-- 1-4. STORES (오프라인 매장)
CREATE TABLE STORES (
    STORE_NUM     NUMBER PRIMARY KEY,
    STORE_NAME    VARCHAR2(50) NOT NULL,
    STORE_ADDRED  VARCHAR2(200) NOT NULL,
    STORE_PHONE   VARCHAR2(20),
    OPEN_TIME     VARCHAR2(30),
    STORE_USE_YN  CHAR(1) DEFAULT 'Y' NOT NULL
);
CREATE SEQUENCE STORES_SEQ NOCACHE;

-- 1-5. BANNERS (쇼핑몰 배너)
CREATE TABLE BANNERS (
    BANNER_NUM       NUMBER PRIMARY KEY,
    BANNER_TITLE     VARCHAR2(100) NOT NULL,
    BANNER_IMG_URL   VARCHAR2(500) NOT NULL,
    BANNER_LINK_URL  VARCHAR2(500),
    POS              NUMBER(1) NOT NULL,
    BANNER_SORT_NO   NUMBER DEFAULT 0 NOT NULL,
    BANNER_START_DAY DATE NOT NULL,
    BANNER_END_DAY   DATE NOT NULL,
    BANNER_USER_YN   CHAR(1) DEFAULT 'Y' NOT NULL
);
CREATE SEQUENCE BANNERS_SEQ NOCACHE;


--------------------------------------------------------
-- 2. 1차 자식 테이블 생성
--------------------------------------------------------

-- 2-1. USERS_DETAIL (회원 상세정보)
CREATE TABLE USERS_DETAIL (
    USER_NUM        NUMBER PRIMARY KEY,
    USER_NAME       VARCHAR2(30) NOT NULL,
    PWD             VARCHAR2(255) NOT NULL,
    PHONE           VARCHAR2(15) NOT NULL,
    EMAIL           VARCHAR2(50) NOT NULL,
    ZIPCODE         VARCHAR2(5) NOT NULL,
    ADDR1           VARCHAR2(120) NOT NULL,
    ADDR2           VARCHAR2(90),
    GRADE           NUMBER(1) DEFAULT 1 NOT NULL,
    USER_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    USER_UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    LAST_LOGIN      DATE,
    CONSTRAINT FK_UDETAIL_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM) ON DELETE CASCADE
);

-- 2-2. PRODUCTS (상품)
-- ※ 주의: 옵션(OPT_NUM)과 이미지(IMG_NUM)는 자식 테이블 참조이므로 순환참조 방지를 위해 FK 제약조건 생략
CREATE TABLE PRODUCTS (
    PROD_NUM        NUMBER PRIMARY KEY,
    CAT_NUM         NUMBER NOT NULL,
    BRAND_NUM       NUMBER NOT NULL,
    OPT_NUM         NUMBER, 
    IMG_NUM         NUMBER, 
    SKU             VARCHAR2(30) UNIQUE NOT NULL,
    PROD_NAME       VARCHAR2(100) NOT NULL,
    GENDER          NUMBER(1) DEFAULT 0 NOT NULL,
    PROD_PRICE      NUMBER NOT NULL,
    SALE_RATE       NUMBER(3) DEFAULT 1 NOT NULL,
    PROD_TEXT       CLOB,
    PROD_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    PROD_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    PROD_UPDATED_AT DATE DEFAULT SYSDATE,
    CONSTRAINT FK_PROD_CAT FOREIGN KEY (CAT_NUM) REFERENCES CATEGORIES(CAT_NUM),
    CONSTRAINT FK_PROD_BRAND FOREIGN KEY (BRAND_NUM) REFERENCES BRANDS(BRAND_NUM)
);
CREATE SEQUENCE PRODUCTS_SEQ NOCACHE;

-- 2-3. ORDERS (주문)
CREATE TABLE ORDERS (
    ORDER_NUM        NUMBER PRIMARY KEY,
    USER_NUM         NUMBER NOT NULL,
    TOTAL_PRICE      INT NOT NULL,
    DISC_PRICE       INT DEFAULT 1 NOT NULL,
    PAY_PRICE        INT NOT NULL,
    RECV_NAME        VARCHAR2(20) NOT NULL,
    RECV_PHONE       VARCHAR2(20) NOT NULL,
    RECV_ZIP         VARCHAR2(10) NOT NULL,
    RECV_ADDR1       VARCHAR2(200) NOT NULL,
    RECV_ADDR2       VARCHAR2(100),
    ORDER_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    ORDER_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    ORDER_DELETE_AT  DATE,
    CONSTRAINT FK_ORD_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM)
);
CREATE SEQUENCE ORDERS_SEQ NOCACHE;

-- 2-4. CHAT_ROOMS (채팅방)
CREATE TABLE CHAT_ROOMS (
    ROOM_NUM       NUMBER PRIMARY KEY,
    USER_NUM       NUMBER NOT NULL,
    ROOM_STATUS    NUMBER DEFAULT 1 NOT NULL,
    ROOM_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    ROOM_CLOSE_AT  DATE,
    CONSTRAINT FK_CHAT_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM)
);
CREATE SEQUENCE CHAT_ROOMS_SEQ NOCACHE;

-- 2-5. NOTIFY (알림)
CREATE TABLE NOTIFY (
    NOTIFY_NUM        NUMBER PRIMARY KEY,
    USER_NUM          NUMBER NOT NULL,
    NOTIFY_TYPE       NUMBER(1) NOT NULL,
    NOTIFY_TITLE      VARCHAR2(100) NOT NULL,
    NOTIFY_CONTENT    VARCHAR2(500) NOT NULL,
    REF_ID            NUMBER,
    READ_YN           CHAR(1) DEFAULT 'N' NOT NULL,
    NOTIFY_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_NOTI_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM)
);
CREATE SEQUENCE NOTIFY_SEQ NOCACHE;


--------------------------------------------------------
-- 3. 2차 자식 테이블 생성 (상품/주문에 의존)
--------------------------------------------------------

-- 3-1. PROD_OPTIONS (상품 옵션)
CREATE TABLE PROD_OPTIONS (
    OPT_NUM      NUMBER PRIMARY KEY,
    PROD_NUM     NUMBER NOT NULL,
    SIZE_VAL     NUMBER(5) NOT NULL,
    COLOR        VARCHAR2(50) NOT NULL,
    ADD_PRICE    INT DEFAULT 0,
    PROD_USE_YN  CHAR(1) DEFAULT '1' NOT NULL,
    CONSTRAINT FK_OPT_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE PROD_OPTIONS_SEQ NOCACHE;

-- 3-2. PROD_IMGS (상품 이미지)
CREATE TABLE PROD_IMGS (
    PROD_IMG_NUM     NUMBER PRIMARY KEY,
    PROD_NUM         NUMBER NOT NULL,
    PROD_IMG_URL     VARCHAR2(500) NOT NULL,
    IS_MAIN          CHAR(1) DEFAULT 'N' NOT NULL,
    PROD_IMG_SORT_NO NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT FK_IMG_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE PROD_IMGS_SEQ NOCACHE;

-- 3-3. WISHLIST (즐겨찾기)
CREATE TABLE WISHLIST (
    WISH_NUM        NUMBER PRIMARY KEY,
    USER_NUM        NUMBER NOT NULL,
    PROD_NUM        NUMBER NOT NULL,
    WISH_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_WISH_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM) ON DELETE CASCADE,
    CONSTRAINT FK_WISH_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE WISHLIST_SEQ NOCACHE;

-- 3-4. PAYMENTS (결제)
CREATE TABLE PAYMENTS (
    PAY_NUM         NUMBER PRIMARY KEY,
    ORDER_NUM       NUMBER NOT NULL,
    METHOD          VARCHAR2(20) NOT NULL,
    TID             VARCHAR2(50),
    AMOUNT          INT NOT NULL,
    PAY_STATUS      NUMBER(1) DEFAULT 1 NOT NULL,
    PAID_AT         DATE,
    PAY_CANCELED_AT DATE,
    CONSTRAINT FK_PAY_ORD FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE PAYMENTS_SEQ NOCACHE;

-- 3-5. CHAT_MSGS (채팅 메시지)
CREATE TABLE CHAT_MSGS (
    MSG_NUM        NUMBER PRIMARY KEY,
    ROOM_NUM       NUMBER NOT NULL,
    MSG_SENDER     NUMBER NOT NULL,
    MSG_CONTENT    CLOB NOT NULL,
    MSG_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    IS_READ        NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT FK_MSG_ROOM FOREIGN KEY (ROOM_NUM) REFERENCES CHAT_ROOMS(ROOM_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE CHAT_MSGS_SEQ NOCACHE;

-- 3-6. DELIVERY (배송)
CREATE TABLE DELIVERY (
    DLV_NUM        NUMBER PRIMARY KEY,
    ORDER_NUM      NUMBER UNIQUE NOT NULL,
    COURIER        VARCHAR2(30),
    INVOICE_NO     VARCHAR2(50),
    DLV_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    DLV_SHIPPED_AT DATE,
    DLV_DONE_AT    DATE,
    CONSTRAINT FK_DLV_ORD FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE DELIVERY_SEQ NOCACHE;


--------------------------------------------------------
-- 4. 3차 자식 테이블 생성 (옵션까지 얽힌 복합 테이블)
--------------------------------------------------------

-- 4-1. REVIEWS (리뷰)
CREATE TABLE REVIEWS (
    REVIEW_NUM        NUMBER PRIMARY KEY,
    USER_NUM          NUMBER NOT NULL,
    PROD_NUM          NUMBER NOT NULL,
    ORDER_NUM         NUMBER NOT NULL,
    RATING            NUMBER(1) NOT NULL,
    REVIEW_CONTENT    VARCHAR2(1000) NOT NULL,
    REVIEW_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    REVIEW_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    REVIEW_UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_REV_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM),
    CONSTRAINT FK_REV_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM),
    CONSTRAINT FK_REV_ORD FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM)
);
CREATE SEQUENCE REVIEWS_SEQ NOCACHE;

-- 4-2. ORDER_ITEMS (주문 상품)
CREATE TABLE ORDER_ITEMS (
    ITEM_NUM        NUMBER PRIMARY KEY,
    ORDER_NUM       NUMBER NOT NULL,
    PROD_NUM        NUMBER NOT NULL,
    OPT_NUM         NUMBER NOT NULL,
    ORDER_ITEM_QTY  INT NOT NULL,
    ORDER_ITEM_PRICE INT NOT NULL,
    CONSTRAINT FK_OITEM_ORD FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM) ON DELETE CASCADE,
    CONSTRAINT FK_OITEM_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM),
    CONSTRAINT FK_OITEM_OPT FOREIGN KEY (OPT_NUM) REFERENCES PROD_OPTIONS(OPT_NUM)
);
CREATE SEQUENCE ORDER_ITEMS_SEQ NOCACHE;

-- 4-3. CART (장바구니)
CREATE TABLE CART (
    CART_NUM        NUMBER PRIMARY KEY,
    USER_NUM        NUMBER NOT NULL,
    OPT_NUM         NUMBER NOT NULL,
    CART_QTY        INT NOT NULL,
    CART_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_CART_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM) ON DELETE CASCADE,
    CONSTRAINT FK_CART_OPT FOREIGN KEY (OPT_NUM) REFERENCES PROD_OPTIONS(OPT_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE CART_SEQ NOCACHE;

-- 4-4. STOCK (재고)
CREATE TABLE STOCK (
    STOCK_NUM        NUMBER PRIMARY KEY,
    OPT_NUM          NUMBER UNIQUE NOT NULL,
    PROD_NUM         NUMBER NOT NULL,
    STOCK_QTY        INT DEFAULT 0 NOT NULL,
    STOCK_MIN_QTY    INT DEFAULT 10 NOT NULL,
    STOCK_UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_STK_OPT FOREIGN KEY (OPT_NUM) REFERENCES PROD_OPTIONS(OPT_NUM) ON DELETE CASCADE,
    CONSTRAINT FK_STK_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE STOCK_SEQ NOCACHE;

-- 4-5. INBOUND (입고)
CREATE TABLE INBOUND (
    IN_NUM         NUMBER PRIMARY KEY,
    OPT_NUM        NUMBER NOT NULL,
    PROD_NUM       NUMBER NOT NULL,
    IN_QTY         INT NOT NULL,
    USER_NUM      NUMBER NOT NULL, 		--관리자(9) 사용
    IN_MEMO        VARCHAR2(300),
    IN_DATE        DATE DEFAULT SYSDATE NOT NULL,
    IN_CREATED_AT  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_INB_OPT FOREIGN KEY (OPT_NUM) REFERENCES PROD_OPTIONS(OPT_NUM),
    CONSTRAINT FK_INB_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM),
    CONSTRAINT FK_INB_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM)
);
CREATE SEQUENCE INBOUND_SEQ NOCACHE;

-- 4-6. OUTBOUND (출고)
CREATE TABLE OUTBOUND (
    OUT_NUM         NUMBER PRIMARY KEY,
    ORDER_NUM       NUMBER NOT NULL,
    OPT_NUM         NUMBER NOT NULL,
    OUT_QTY         INT NOT NULL,
    USER_NUM       NUMBER NOT NULL, 			--관리자(9) 사용
    OUT_DATE        DATE DEFAULT SYSDATE NOT NULL,
    OUT_CREATED_AT  DATE DEFAULT SYSDATE NOT NULL,
    OUT_MEMO        VARCHAR2(300),
    CONSTRAINT FK_OUT_ORD FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM),
    CONSTRAINT FK_OUT_OPT FOREIGN KEY (OPT_NUM) REFERENCES PROD_OPTIONS(OPT_NUM),
    CONSTRAINT FK_OUT_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM)
);
CREATE SEQUENCE OUTBOUND_SEQ NOCACHE;

-- 4-7. RETURNS (반품/교환)
CREATE TABLE RETURNS (
    RET_NUM        NUMBER PRIMARY KEY,
    ORDER_NUM      NUMBER NOT NULL,
    USER_NUM       NUMBER NOT NULL,
    TP             NUMBER(1) NOT NULL, 
    REASON         VARCHAR2(200) NOT NULL,
    PROD_NUM       NUMBER NOT NULL,
    OPT_NUM        NUMBER, 
    RET_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    RET_NOTE       VARCHAR2(300),
    IS_GOOD        NUMBER(1),
    RET_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    RET_UPDATED_AT DATE,
    CONSTRAINT FK_RET_ORD FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM),
    CONSTRAINT FK_RET_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM),
    CONSTRAINT FK_RET_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM),
    CONSTRAINT FK_RET_OPT FOREIGN KEY (OPT_NUM) REFERENCES PROD_OPTIONS(OPT_NUM)
);
CREATE SEQUENCE RETURNS_SEQ NOCACHE;

-- 4-8. RESTOCK_ALERT (재입고 알림)
CREATE TABLE RESTOCK_ALERT (
    ALERT_NUM        NUMBER PRIMARY KEY,
    USER_NUM         NUMBER NOT NULL,
    OPT_NUM          NUMBER NOT NULL,
    SENT_YN          CHAR(1) DEFAULT 'N' NOT NULL,
    ALERT_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_RSTK_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM) ON DELETE CASCADE,
    CONSTRAINT FK_RSTK_OPT FOREIGN KEY (OPT_NUM) REFERENCES PROD_OPTIONS(OPT_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE RESTOCK_ALERT_SEQ NOCACHE;


