--------------------------------------------------------
-- 1. 최상위 부모 테이블
--------------------------------------------------------

-- 1-1. USERS
CREATE TABLE USERS (
    USER_NUM NUMBER PRIMARY KEY,
    USER_ID  VARCHAR2(12) UNIQUE NOT NULL,
    AUTH     NUMBER(1) DEFAULT 2 NOT NULL
);
CREATE SEQUENCE USERS_SEQ NOCACHE;

-- 1-2. CATEGORIES
CREATE TABLE CATEGORIES (
    CAT_NUM     NUMBER PRIMARY KEY,
    CAT_NAME    VARCHAR2(30) NOT NULL,
    CAT_ICON    VARCHAR2(10),
    CAT_SORT_NO NUMBER DEFAULT 0 NOT NULL,
    CAT_USE_YN  CHAR(1) DEFAULT 'Y' NOT NULL
);
CREATE SEQUENCE CATEGORIES_SEQ NOCACHE;

-- 1-3. BRANDS
CREATE TABLE BRANDS (
    BRAND_NUM    NUMBER PRIMARY KEY,
    BRAND_NAME   VARCHAR2(50) NOT NULL,
    BRAND_USE_YN CHAR(1) DEFAULT 'Y' NOT NULL
);
CREATE SEQUENCE BRANDS_SEQ NOCACHE;

-- 1-4. STORES
CREATE TABLE STORES (
    STORE_NUM    NUMBER PRIMARY KEY,
    STORE_NAME   VARCHAR2(50) NOT NULL,
    STORE_ADDR   VARCHAR2(200) NOT NULL, 
    STORE_PHONE  VARCHAR2(20),
    OPEN_TIME    VARCHAR2(30),
    STORE_USE_YN CHAR(1) DEFAULT 'Y' NOT NULL
);
CREATE SEQUENCE STORES_SEQ NOCACHE;

-- 1-5. BANNERS
CREATE TABLE BANNERS (
    BANNER_NUM       NUMBER PRIMARY KEY,
    BANNER_TITLE     VARCHAR2(100) NOT NULL,
    BANNER_IMG_URL   VARCHAR2(500) NOT NULL,
    BANNER_LINK_URL  VARCHAR2(500),
    POS              NUMBER(1) NOT NULL,
    BANNER_SORT_NO   NUMBER DEFAULT 0 NOT NULL,
    BANNER_START_DAY DATE NOT NULL,
    BANNER_END_DAY   DATE NOT NULL,
    BANNER_USE_YN    CHAR(1) DEFAULT 'Y' NOT NULL
);
CREATE SEQUENCE BANNERS_SEQ NOCACHE;


--------------------------------------------------------
-- 2. 1차 자식 테이블
--------------------------------------------------------

-- 2-1. USERS_DETAIL
CREATE TABLE USERS_DETAIL (
    USER_NUM        NUMBER PRIMARY KEY,
    USER_NAME       VARCHAR2(30) NOT NULL,
    PWD             VARCHAR2(255) NOT NULL,
    PHONE           VARCHAR2(15),
    EMAIL           VARCHAR2(50),
    ZIPCODE         VARCHAR2(5),
    ADDR1           VARCHAR2(120),
    ADDR2           VARCHAR2(90),
    GRADE           NUMBER(1) DEFAULT 1 NOT NULL,
    USER_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    USER_UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    LAST_LOGIN      DATE,
    TOTAL_AMOUNT	NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT FK_UDETAIL_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM) ON DELETE CASCADE
);

-- 2-2. PRODUCTS ← OPT_NUM, IMG_NUM FK 제약 없이 유지 (순환참조 방지)
CREATE TABLE PRODUCTS (
    PROD_NUM        NUMBER PRIMARY KEY,
    CAT_NUM         NUMBER NOT NULL,
    BRAND_NUM       NUMBER NOT NULL,
    OPT_NUM         NUMBER,
    IMG_NUM         NUMBER,
    SKU             VARCHAR2(30) UNIQUE NOT NULL,
    PROD_NAME       VARCHAR2(100) NOT NULL,
    GENDER          NUMBER(1) DEFAULT 0 NOT NULL,
    PROD_PRICE      NUMBER NOT NULL,
    SALE_RATE       NUMBER(3) DEFAULT 0 NOT NULL,
    PROD_TEXT       CLOB,
    PROD_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    PROD_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    PROD_UPDATED_AT DATE DEFAULT SYSDATE,
    CONSTRAINT FK_PROD_CAT   FOREIGN KEY (CAT_NUM)   REFERENCES CATEGORIES(CAT_NUM),
    CONSTRAINT FK_PROD_BRAND FOREIGN KEY (BRAND_NUM) REFERENCES BRANDS(BRAND_NUM)
);
CREATE SEQUENCE PRODUCTS_SEQ NOCACHE;

-- 2-3. ORDERS
CREATE TABLE ORDERS (
    ORDER_NUM        NUMBER PRIMARY KEY,
    USER_NUM         NUMBER NOT NULL,
    TOTAL_PRICE      NUMBER NOT NULL,
    DISC_PRICE       NUMBER DEFAULT 0 NOT NULL,
    PAY_PRICE        NUMBER NOT NULL,
    RECV_NAME        VARCHAR2(20) NOT NULL,
    RECV_PHONE       VARCHAR2(20) NOT NULL,
    RECV_ZIP         VARCHAR2(10) NOT NULL,
    RECV_ADDR1       VARCHAR2(200) NOT NULL,
    RECV_ADDR2       VARCHAR2(100),
    ORDER_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    ORDER_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    ORDER_DELETE_AT  DATE,
    CONSTRAINT FK_ORD_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM)
);
CREATE SEQUENCE ORDERS_SEQ NOCACHE;

-- 2-4. CHAT_ROOMS
CREATE TABLE CHAT_ROOMS (
    ROOM_NUM        NUMBER PRIMARY KEY,
    USER_NUM        NUMBER NOT NULL,
    ADMIN_NUM       NUMBER,                
    ROOM_STATUS     NUMBER DEFAULT 1 NOT NULL,
    ROOM_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    ROOM_CLOSE_AT   DATE,
    CONSTRAINT FK_CHAT_USER  FOREIGN KEY (USER_NUM)  REFERENCES USERS(USER_NUM),
    CONSTRAINT FK_CHAT_ADMIN FOREIGN KEY (ADMIN_NUM) REFERENCES USERS(USER_NUM) 
);
CREATE SEQUENCE CHAT_ROOMS_SEQ NOCACHE;

-- 2-5. NOTIFY
CREATE TABLE NOTIFY (
    NOTIFY_NUM        NUMBER PRIMARY KEY,
    USER_NUM          NUMBER NOT NULL,
    NOTIFY_TYPE       NUMBER(1) NOT NULL,
    NOTIFY_TITLE      VARCHAR2(100) NOT NULL,
    NOTIFY_CONTENT    VARCHAR2(500) NOT NULL,
    REF_ID            NUMBER,
    READ_YN           CHAR(1) DEFAULT 'N' NOT NULL,
    NOTIFY_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_NOTI_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM)
);
CREATE SEQUENCE NOTIFY_SEQ NOCACHE;


