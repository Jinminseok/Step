-- 3. 2차 자식 테이블
--------------------------------------------------------

-- 3-1. PROD_OPTIONS 
CREATE TABLE PROD_OPTIONS (
    OPT_NUM     NUMBER PRIMARY KEY,
    PROD_NUM    NUMBER NOT NULL,
    SIZE_VAL    NUMBER(5) NOT NULL,
    COLOR       VARCHAR2(50) NOT NULL,
    ADD_PRICE   NUMBER DEFAULT 0,
    PROD_USE_YN CHAR(1) DEFAULT 'Y' NOT NULL, 
    CONSTRAINT FK_OPT_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE PROD_OPTIONS_SEQ NOCACHE;

-- 3-2. PROD_IMGS
CREATE TABLE PROD_IMGS (
    PROD_IMG_NUM     NUMBER PRIMARY KEY,
    PROD_NUM         NUMBER NOT NULL,
    PROD_IMG_URL     VARCHAR2(500) NOT NULL,
    IS_MAIN          CHAR(1) DEFAULT 'N' NOT NULL,
    PROD_IMG_SORT_NO NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT FK_IMG_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE PROD_IMGS_SEQ NOCACHE;

-- 3-3. WISHLIST
CREATE TABLE WISHLIST (
    WISH_NUM        NUMBER PRIMARY KEY,
    USER_NUM        NUMBER NOT NULL,
    PROD_NUM        NUMBER NOT NULL,
    WISH_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_WISH_USER FOREIGN KEY (USER_NUM)  REFERENCES USERS(USER_NUM)    ON DELETE CASCADE,
    CONSTRAINT FK_WISH_PROD FOREIGN KEY (PROD_NUM)  REFERENCES PRODUCTS(PROD_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE WISHLIST_SEQ NOCACHE;

-- 3-4. PAYMENTS
CREATE TABLE PAYMENTS (
    PAY_NUM         NUMBER PRIMARY KEY,
    ORDER_NUM       NUMBER NOT NULL,
    METHOD          VARCHAR2(20) NOT NULL,
    TID             VARCHAR2(50),
    AMOUNT          NUMBER NOT NULL,
    PAY_STATUS      NUMBER(1) DEFAULT 1 NOT NULL,
    PAID_AT         DATE,
    PAY_CANCELED_AT DATE,
    CONSTRAINT FK_PAY_ORD FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE PAYMENTS_SEQ NOCACHE;

-- 3-5. CHAT_MSGS ← MSG_SENDER_NUM 컬럼 추가
CREATE TABLE CHAT_MSGS (
    MSG_NUM        NUMBER PRIMARY KEY,
    ROOM_NUM       NUMBER NOT NULL,
    MSG_SENDER     NUMBER NOT NULL,
    MSG_SENDER_NUM NUMBER NOT NULL,           
    MSG_CONTENT    CLOB NOT NULL,
    MSG_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    IS_READ        NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT FK_MSG_ROOM        FOREIGN KEY (ROOM_NUM)       REFERENCES CHAT_ROOMS(ROOM_NUM) ON DELETE CASCADE,
    CONSTRAINT FK_MSG_SENDER_USER FOREIGN KEY (MSG_SENDER_NUM) REFERENCES USERS(USER_NUM)   );
CREATE SEQUENCE CHAT_MSGS_SEQ NOCACHE;

-- 3-6. DELIVERY
CREATE TABLE DELIVERY (
    DLV_NUM        NUMBER PRIMARY KEY,
    ORDER_NUM      NUMBER UNIQUE NOT NULL,
    COURIER        VARCHAR2(30),
    INVOICE_NO     VARCHAR2(50),
    DLV_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    DLV_SHIPPED_AT DATE,
    DLV_DONE_AT    DATE,
    CONSTRAINT FK_DLV_ORD FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM) ON DELETE CASCADE
);
CREATE SEQUENCE DELIVERY_SEQ NOCACHE;


--------------------------------------------------------
-- 4. 3차 자식 테이블
--------------------------------------------------------

-- 4-1. REVIEWS
CREATE TABLE REVIEWS (
    REVIEW_NUM        NUMBER PRIMARY KEY,
    USER_NUM          NUMBER NOT NULL,
    PROD_NUM          NUMBER NOT NULL,
    ORDER_NUM         NUMBER NOT NULL,
    RATING            NUMBER(1) NOT NULL,
    REVIEW_CONTENT    VARCHAR2(1000) NOT NULL,
    REVIEW_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    REVIEW_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    REVIEW_UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_REV_USER FOREIGN KEY (USER_NUM)  REFERENCES USERS(USER_NUM),
    CONSTRAINT FK_REV_PROD FOREIGN KEY (PROD_NUM)  REFERENCES PRODUCTS(PROD_NUM),
    CONSTRAINT FK_REV_ORD  FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM)
);
CREATE SEQUENCE REVIEWS_SEQ NOCACHE;

-- 4-2. ORDER_ITEMS
CREATE TABLE ORDER_ITEMS (
    ITEM_NUM         NUMBER PRIMARY KEY,
    ORDER_NUM        NUMBER NOT NULL,
    PROD_NUM         NUMBER NOT NULL,
    OPT_NUM          NUMBER NOT NULL,
    ORDER_ITEM_QTY   NUMBER NOT NULL,
    ORDER_ITEM_PRICE NUMBER NOT NULL,
    CONSTRAINT FK_OITEM_ORD  FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM)       ON DELETE CASCADE,
    CONSTRAINT FK_OITEM_PROD FOREIGN KEY (PROD_NUM)  REFERENCES PRODUCTS(PROD_NUM),
    CONSTRAINT FK_OITEM_OPT  FOREIGN KEY (OPT_NUM)   REFERENCES PROD_OPTIONS(OPT_NUM)
);
CREATE SEQUENCE ORDER_ITEMS_SEQ NOCACHE;

-- 4-3. CART
CREATE TABLE CART (
    CART_NUM        NUMBER PRIMARY KEY,
    USER_NUM        NUMBER NOT NULL,
    OPT_NUM         NUMBER NOT NULL,
    CART_QTY        NUMBER NOT NULL,
    CART_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_CART_USER FOREIGN KEY (USER_NUM) REFERENCES USERS(USER_NUM)          ON DELETE CASCADE,
    CONSTRAINT FK_CART_OPT  FOREIGN KEY (OPT_NUM)  REFERENCES PROD_OPTIONS(OPT_NUM)   ON DELETE CASCADE
);
CREATE SEQUENCE CART_SEQ NOCACHE;

-- 4-4. STOCK
CREATE TABLE STOCK (
    STOCK_NUM        NUMBER PRIMARY KEY,
    OPT_NUM          NUMBER UNIQUE NOT NULL,
    PROD_NUM         NUMBER NOT NULL,
    STOCK_QTY        NUMBER DEFAULT 0 NOT NULL,
    STOCK_MIN_QTY    NUMBER DEFAULT 10 NOT NULL,
    STOCK_UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_STK_OPT  FOREIGN KEY (OPT_NUM)  REFERENCES PROD_OPTIONS(OPT_NUM) ON DELETE CASCADE,
    CONSTRAINT FK_STK_PROD FOREIGN KEY (PROD_NUM) REFERENCES PRODUCTS(PROD_NUM)    ON DELETE CASCADE
);
CREATE SEQUENCE STOCK_SEQ NOCACHE;

-- 4-5. INBOUND 
CREATE TABLE INBOUND (
    IN_NUM        NUMBER PRIMARY KEY,
    OPT_NUM       NUMBER NOT NULL,
    PROD_NUM      NUMBER NOT NULL,
    IN_QTY        NUMBER NOT NULL,
    ADMIN_NUM     NUMBER NOT NULL,              
    IN_MEMO       VARCHAR2(300),
    IN_DATE       DATE DEFAULT SYSDATE NOT NULL,
    IN_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    IN_STATUS     NUMBER(1) DEFAULT 1 NOT NULL, 
    SUPPLIER      VARCHAR2(100),                
    CONSTRAINT FK_INB_OPT   FOREIGN KEY (OPT_NUM)   REFERENCES PROD_OPTIONS(OPT_NUM),
    CONSTRAINT FK_INB_PROD  FOREIGN KEY (PROD_NUM)  REFERENCES PRODUCTS(PROD_NUM),
    CONSTRAINT FK_INB_ADMIN FOREIGN KEY (ADMIN_NUM) REFERENCES USERS(USER_NUM)  
);
CREATE SEQUENCE INBOUND_SEQ NOCACHE;

-- 4-6. OUTBOUND ← USER_NUM → ADMIN_NUM 변경 + OUT_STATUS 추가
CREATE TABLE OUTBOUND (
    OUT_NUM        NUMBER PRIMARY KEY,
    ORDER_NUM      NUMBER NOT NULL,
    OPT_NUM        NUMBER NOT NULL,
    OUT_QTY        NUMBER NOT NULL,
    ADMIN_NUM      NUMBER NOT NULL,              
    OUT_DATE       DATE DEFAULT SYSDATE NOT NULL,
    OUT_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    OUT_MEMO       VARCHAR2(300),
    OUT_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_OUT_ORD   FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM),
    CONSTRAINT FK_OUT_OPT   FOREIGN KEY (OPT_NUM)   REFERENCES PROD_OPTIONS(OPT_NUM),
    CONSTRAINT FK_OUT_ADMIN FOREIGN KEY (ADMIN_NUM) REFERENCES USERS(USER_NUM)     
);
CREATE SEQUENCE OUTBOUND_SEQ NOCACHE;

-- 4-7. RETURNS 
CREATE TABLE RETURNS (
    RET_NUM        NUMBER PRIMARY KEY,
    ORDER_NUM      NUMBER NOT NULL,
    USER_NUM       NUMBER NOT NULL,
    TP             NUMBER(1) NOT NULL,
    REASON         VARCHAR2(200) NOT NULL,
    PROD_NUM       NUMBER NOT NULL,
    OPT_NUM        NUMBER,
    RET_STATUS     NUMBER(1) DEFAULT 1 NOT NULL,
    ADMIN_NUM      NUMBER,                      
    RET_NOTE       VARCHAR2(300),
    IS_GOOD        NUMBER(1),
    RET_CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    RET_UPDATED_AT DATE,
    CONSTRAINT FK_RET_ORD   FOREIGN KEY (ORDER_NUM) REFERENCES ORDERS(ORDER_NUM),
    CONSTRAINT FK_RET_USER  FOREIGN KEY (USER_NUM)  REFERENCES USERS(USER_NUM),
    CONSTRAINT FK_RET_PROD  FOREIGN KEY (PROD_NUM)  REFERENCES PRODUCTS(PROD_NUM),
    CONSTRAINT FK_RET_OPT   FOREIGN KEY (OPT_NUM)   REFERENCES PROD_OPTIONS(OPT_NUM),
    CONSTRAINT FK_RET_ADMIN FOREIGN KEY (ADMIN_NUM) REFERENCES USERS(USER_NUM)   
);
CREATE SEQUENCE RETURNS_SEQ NOCACHE;

-- 4-8. RESTOCK_ALERT
CREATE TABLE RESTOCK_ALERT (
